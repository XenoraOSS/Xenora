//! `xenora imports coverage`: what the standard service registry provides,
//! set against what the import metadata says about the same symbols.
//!
//! The report is built from the registry and the built-in symbol database
//! alone, so the same source tree always produces the same bytes. It does not
//! read executables, the network or the clock.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::process::ExitCode;
use std::sync::Arc;
use xenora_import_gen::{Classification, SymbolDb};
use xenora_loader::ImportRegistry;
use xenora_loader::import_table::ImportName;
use xenora_loader::imports::ServiceStatus;
use xenora_loader::services::{MockClock, ServicesState, register_standard_services};

const DEFAULT_OUT: &str = "artifacts/coverage/api-coverage.md";

#[derive(Default)]
struct Counts {
    implemented: usize,
    partial: usize,
    stub: usize,
    aliases: usize,
}

/// Render the report.
pub fn render() -> String {
    let mut registry = ImportRegistry::new();
    register_standard_services(
        &mut registry,
        Arc::new(ServicesState::new(Arc::new(MockClock::new(0)))),
    );
    let db = SymbolDb::builtin();

    let mut modules: BTreeMap<String, Counts> = BTreeMap::new();
    let mut services: Vec<(String, String, ServiceStatus)> = registry
        .iter_registered()
        .map(|(module, symbol, status)| (module.to_ascii_lowercase(), symbol.to_owned(), status))
        .collect();
    services.sort_by(|a, b| (&a.0, &a.1).cmp(&(&b.0, &b.1)));
    for (module, _, status) in &services {
        let counts = modules.entry(module.clone()).or_default();
        match status {
            ServiceStatus::Implemented => counts.implemented += 1,
            ServiceStatus::Partial => counts.partial += 1,
            ServiceStatus::Stub => counts.stub += 1,
        }
    }
    let mut aliases: Vec<(String, String, String)> = registry
        .iter_aliases()
        .map(|(module, symbol, target)| {
            (
                module.to_owned(),
                symbol.to_owned(),
                target.to_ascii_lowercase(),
            )
        })
        .collect();
    aliases.sort();
    for (module, _, _) in &aliases {
        modules.entry(module.clone()).or_default().aliases += 1;
    }

    // Metadata the registry contradicts, in either direction.
    let mut unclassified = Vec::new();
    let mut disagreeing = Vec::new();
    for (module, symbol, status) in &services {
        match db.get(module, symbol) {
            None => unclassified.push(format!("`{module}!{symbol}` ({})", status.as_str())),
            Some(Classification::StandardService) => {}
            Some(class) => disagreeing.push(format!(
                "`{module}!{symbol}`: registered {}, metadata says {}",
                status.as_str(),
                class.tier_name()
            )),
        }
    }
    let mut missing = Vec::new();
    for (module, symbol, class) in db.entries() {
        if matches!(class, Classification::StandardService)
            && registry
                .resolve(module, &ImportName::Name(symbol.to_owned()))
                .is_none()
        {
            missing.push(format!("`{module}!{symbol}`"));
        }
    }

    let total = |pick: fn(&Counts) -> usize| modules.values().map(pick).sum::<usize>();
    let mut md = String::new();
    let _ = writeln!(md, "# Runtime API coverage");
    let _ = writeln!(md);
    let _ = writeln!(
        md,
        "Generated by `xenora imports coverage` from the standard service registry and the built-in import metadata. Do not edit."
    );
    let _ = writeln!(md);
    let _ = writeln!(
        md,
        "A registered service is not a compatibility claim. `implemented` and `partial` describe behaviour against the documented contract for synthetic guests; no service has been independently accepted, and no Xbox or commercial game has run."
    );
    let _ = writeln!(md);
    let _ = writeln!(md, "## Totals");
    let _ = writeln!(md);
    let _ = writeln!(md, "| Measure | Count |");
    let _ = writeln!(md, "| --- | ---: |");
    let _ = writeln!(md, "| Services | {} |", services.len());
    let _ = writeln!(md, "| Implemented | {} |", total(|c| c.implemented));
    let _ = writeln!(md, "| Partial | {} |", total(|c| c.partial));
    let _ = writeln!(md, "| Stub | {} |", total(|c| c.stub));
    let _ = writeln!(md, "| Aliases (not services) | {} |", aliases.len());
    let _ = writeln!(
        md,
        "| Registered but not in metadata | {} |",
        unclassified.len()
    );
    let _ = writeln!(
        md,
        "| Metadata disagrees with registry | {} |",
        disagreeing.len()
    );
    let _ = writeln!(
        md,
        "| Metadata expects a service that is missing | {} |",
        missing.len()
    );
    let _ = writeln!(md);
    let _ = writeln!(md, "## By module");
    let _ = writeln!(md);
    let _ = writeln!(md, "| Module | Implemented | Partial | Stub | Aliases |");
    let _ = writeln!(md, "| --- | ---: | ---: | ---: | ---: |");
    for (module, c) in &modules {
        let _ = writeln!(
            md,
            "| `{module}` | {} | {} | {} | {} |",
            c.implemented, c.partial, c.stub, c.aliases
        );
    }
    for (title, list) in [
        ("Metadata expects a service that is missing", &missing),
        ("Metadata disagrees with registry", &disagreeing),
        ("Registered but not in metadata", &unclassified),
    ] {
        let _ = writeln!(md);
        let _ = writeln!(md, "## {title}");
        let _ = writeln!(md);
        if list.is_empty() {
            let _ = writeln!(md, "None.");
        }
        for line in list {
            let _ = writeln!(md, "- {line}");
        }
    }
    md
}

/// `xenora imports coverage [--out <file>]`
pub fn command(args: &[String]) -> ExitCode {
    let out = match args {
        [] => DEFAULT_OUT.to_owned(),
        [flag, path] if flag == "--out" => path.clone(),
        _ => {
            eprintln!("usage: xenora imports coverage [--out <file>]");
            return ExitCode::from(2);
        }
    };
    let report = render();
    let path = std::path::Path::new(&out);
    if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty())
        && let Err(error) = std::fs::create_dir_all(parent)
    {
        eprintln!("failed to create {}: {error}", parent.display());
        return ExitCode::FAILURE;
    }
    if let Err(error) = std::fs::write(path, &report) {
        eprintln!("failed to write {out}: {error}");
        return ExitCode::FAILURE;
    }
    println!("Coverage report written to: {out}");
    ExitCode::SUCCESS
}
