use objc2::{rc::Retained, runtime::ProtocolObject};
use objc2_metal::{MTLCommandBuffer, MTLCommandQueue, MTLDevice, MTLEvent, MTLSharedEvent};
use std::sync::{
    Arc,
    atomic::{AtomicBool, Ordering},
    mpsc,
};
use std::time::Duration;

// Release before any unwinding drains queued work. The watchdog is rescue only,
// and its release is explicitly a failure, never ordering evidence.
pub(super) struct Gate {
    event: Retained<ProtocolObject<dyn MTLSharedEvent>>,
    timed_out: Arc<AtomicBool>,
    done: Option<mpsc::Sender<()>>,
    watchdog: Option<std::thread::JoinHandle<()>>,
}
impl Gate {
    pub(super) fn new(gpu: &NativeCompute, cohort: &RenderCohort, queue: RenderQueue) -> Self {
        let event = gpu.device().newSharedEvent().unwrap();
        let rescue = event.clone();
        let timed_out = Arc::new(AtomicBool::new(false));
        let timeout_thread = timed_out.clone();
        let (done, receive) = mpsc::channel();
        let watchdog = std::thread::spawn(move || {
            if receive.recv_timeout(Duration::from_secs(10)).is_err() {
                timeout_thread.store(true, Ordering::SeqCst);
                rescue.setSignaledValue(1);
            }
        });
        let command = cohort.queue(queue).commandBuffer().unwrap();
        let event_ref: &ProtocolObject<dyn MTLEvent> = ProtocolObject::from_ref(&*event);
        command.encodeWaitForEvent_value(event_ref, 1);
        command.commit();
        Self {
            event,
            timed_out,
            done: Some(done),
            watchdog: Some(watchdog),
        }
    }
    pub(super) fn observe_then_release(
        mut self,
        gpu: &NativeCompute,
        cohort: &RenderCohort,
        consumer: RenderQueue,
    ) {
        let committed_held =
            self.event.signaledValue() == 0 && !self.timed_out.load(Ordering::SeqCst);
        let completed = gpu.device().newSharedEvent().unwrap();
        let marker = cohort.queue(consumer).commandBuffer().unwrap();
        let event_ref: &ProtocolObject<dyn MTLEvent> = ProtocolObject::from_ref(&*completed);
        marker.encodeSignalEvent_value(event_ref, 1);
        marker.commit();
        std::thread::sleep(Duration::from_millis(250));
        let early = completed.signaledValue() != 0;
        let observed_held =
            self.event.signaledValue() == 0 && !self.timed_out.load(Ordering::SeqCst);
        self.release();
        assert!(
            committed_held && observed_held && !self.timed_out.load(Ordering::SeqCst),
            "watchdog invalidated gated observation"
        );
        assert!(!early, "consumer GPU marker ran before producer release");
    }
    fn release(&mut self) {
        self.event.setSignaledValue(1);
        if let Some(done) = self.done.take() {
            let _ = done.send(());
        }
        if let Some(watchdog) = self.watchdog.take() {
            watchdog.join().unwrap();
        }
    }
}
impl Drop for Gate {
    fn drop(&mut self) {
        self.release();
    }
}

const SOURCE_BYTES: [u8; 13] = [3, 251, 17, 129, 64, 7, 223, 41, 155, 2, 199, 83, 237];
const DEST_BYTES: [u8; 17] = [
    101, 102, 103, 104, 105, 106, 107, 108, 109, 110, 111, 112, 113, 114, 115, 116, 117,
];
const PATCHED_BYTES: [u8; 17] = [
    101, 102, 103, 104, 105, 129, 64, 7, 223, 41, 155, 2, 113, 114, 115, 116, 117,
];
fn output_buffer(cohort: &RenderCohort, point: &RenderPoint) -> RenderBufferOutput {
    match cohort.copy_output(point).unwrap() {
        RenderCopyOutput::Buffer(output) => output,
        _ => panic!("expected buffer"),
    }
}
fn assert_bytes(output: OwnedCopyOutput, expected: &[u8]) {
    match output {
        OwnedCopyOutput::Buffer(bytes) => assert_eq!(bytes, expected),
        _ => panic!("expected buffer bytes"),
    }
}
fn patch<'a>(
    source: QueuedCopyInput<'a>,
    destination: QueuedCopyInput<'a>,
) -> QueuedBufferRegionCopy<'a> {
    QueuedBufferRegionCopy {
        source,
        destination,
        source_offset: 3,
        destination_offset: 5,
        byte_len: 7,
    }
}
#[test]
fn queued_unaligned_pending_source_waits_and_retains_input() {
    pending_role(true);
}
#[test]
fn queued_unaligned_pending_destination_waits_and_retains_input() {
    pending_role(false);
}
fn pending_role(pending_source: bool) {
    let gpu = NativeCompute::new().unwrap();
    for producer_first in [false, true] {
        let mut cohort = gpu.new_render_cohort().unwrap();
        let gate = Gate::new(&gpu, &cohort, RenderQueue::First);
        let prior = if pending_source {
            SOURCE_BYTES.as_slice()
        } else {
            DEST_BYTES.as_slice()
        };
        let mut host = prior.to_vec();
        let mut other = if pending_source {
            DEST_BYTES.to_vec()
        } else {
            SOURCE_BYTES.to_vec()
        };
        let producer = cohort
            .submit_copy(RenderQueue::First, QueuedCopyInput::HostBuffer(&host), &[])
            .unwrap();
        let output = output_buffer(&cohort, &producer);
        let request = if pending_source {
            patch(
                QueuedCopyInput::ProducedBuffer(output.clone()),
                QueuedCopyInput::HostBuffer(&other),
            )
        } else {
            patch(
                QueuedCopyInput::HostBuffer(&other),
                QueuedCopyInput::ProducedBuffer(output.clone()),
            )
        };
        let consumer = cohort
            .submit_buffer_region_copy(RenderQueue::Second, request, &[])
            .unwrap();
        host.fill(0);
        other.fill(0);
        drop(host);
        drop(other);
        drop(output);
        gate.observe_then_release(&gpu, &cohort, RenderQueue::Second);
        if producer_first {
            assert_bytes(cohort.collect_copy(&producer).unwrap(), prior);
            drop(producer);
            assert_bytes(cohort.collect_copy(&consumer).unwrap(), &PATCHED_BYTES);
        } else {
            assert_bytes(cohort.collect_copy(&consumer).unwrap(), &PATCHED_BYTES);
            assert_bytes(cohort.collect_copy(&producer).unwrap(), prior);
        }
    }
}

#[test]
fn queued_unaligned_exact_old_versions_remain_immutable_and_stale_rejects() {
    let gpu = NativeCompute::new().unwrap();
    let mut cohort = gpu.new_render_cohort().unwrap();
    let a = cohort
        .submit_copy(
            RenderQueue::First,
            QueuedCopyInput::HostBuffer(&SOURCE_BYTES),
            &[],
        )
        .unwrap();
    let source = output_buffer(&cohort, &a);
    let b = cohort
        .submit_copy(
            RenderQueue::Second,
            QueuedCopyInput::HostBuffer(&DEST_BYTES),
            &[],
        )
        .unwrap();
    let destination = output_buffer(&cohort, &b);
    assert_bytes(cohort.collect_copy(&a).unwrap(), &SOURCE_BYTES);
    assert_bytes(cohort.collect_copy(&b).unwrap(), &DEST_BYTES);
    drop(a);
    drop(b);
    let newer = cohort
        .submit_copy(
            RenderQueue::First,
            QueuedCopyInput::HostBuffer(&[201; 17]),
            &[],
        )
        .unwrap();
    let consumer = cohort
        .submit_buffer_region_copy(
            RenderQueue::Second,
            patch(
                QueuedCopyInput::ProducedBuffer(source.clone()),
                QueuedCopyInput::ProducedBuffer(destination.clone()),
            ),
            &[],
        )
        .unwrap();
    assert_bytes(cohort.collect_copy(&consumer).unwrap(), &PATCHED_BYTES);
    assert_bytes(cohort.collect_copy(&newer).unwrap(), &[201; 17]);
    for (old, expected) in [
        (source.clone(), SOURCE_BYTES.as_slice()),
        (destination.clone(), DEST_BYTES.as_slice()),
    ] {
        let copied = cohort
            .submit_copy(
                RenderQueue::First,
                QueuedCopyInput::ProducedBuffer(old),
                &[],
            )
            .unwrap();
        assert_bytes(cohort.collect_copy(&copied).unwrap(), expected);
    }
    cohort.reinitialize().unwrap();
    for source_side in [false, true] {
        let request = if source_side {
            patch(
                QueuedCopyInput::ProducedBuffer(source.clone()),
                QueuedCopyInput::HostBuffer(&DEST_BYTES),
            )
        } else {
            patch(
                QueuedCopyInput::HostBuffer(&SOURCE_BYTES),
                QueuedCopyInput::ProducedBuffer(destination.clone()),
            )
        };
        assert!(
            cohort
                .submit_buffer_region_copy(RenderQueue::First, request, &[])
                .is_err()
        );
    }
    let recovery = cohort
        .submit_buffer_region_copy(
            RenderQueue::First,
            patch(
                QueuedCopyInput::HostBuffer(&SOURCE_BYTES),
                QueuedCopyInput::HostBuffer(&DEST_BYTES),
            ),
            &[],
        )
        .unwrap();
    assert_bytes(cohort.collect_copy(&recovery).unwrap(), &PATCHED_BYTES);
}

